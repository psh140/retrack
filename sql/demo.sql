-- 포트폴리오 방문자가 가입 없이 시스템 전체를 둘러볼 수 있도록 넣는 표본 데이터다.
-- 로컬 개발용 seed.sql은 그대로 두고, 운영에서는 이 파일만 사용한다.
--
-- **멱등하게 작성한다.** scripts/reset-demo.sh가 이 파일을 매일 재실행해
-- 방문자가 변경·삭제한 데이터를 원상 복구하기 때문이다. 그래서 맨 앞에서 TRUNCATE로
