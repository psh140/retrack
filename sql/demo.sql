--
-- **주의 — 이 스크립트는 USERS 테이블까지 비운다.**
-- 운영 DB에 데모 계정 외의 실제 계정이 있다면 함께 삭제된다. 실행 전 반드시 확인할 것.
--
-- 모든 계정 비밀번호: demo1234!
--   해시는 프로젝트가 실제로 쓰는 BCryptPasswordEncoder(spring-security-crypto 5.8.13)로
--   생성했다. htpasswd로 만들면 $2y$ 접두사가 나와 기존 데이터와 형식이 어긋난다.
--
-- @since 2026-08-03
-- =============================================

